i18n.use({
  type: 'postProcessor',
  name: 'lowercaseFirst',
  process(value, key, options, translator) {
    if (value === key && key.length > 0 && key[0] === key[0].toUpperCase()) {
      const lowerKey = key[0].toLowerCase() + key.slice(1);
      const res = translator.translate(lowerKey, options);
      if (res !== lowerKey) return res;
    }
    return value;
  }
});

