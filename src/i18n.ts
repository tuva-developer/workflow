function capitalizeKeys(obj: Record<string, string>) {
  const result: Record<string, string> = { ...obj };
  Object.keys(obj).forEach(key => {
    if (key.length > 0 && key[0] === key[0].toLowerCase()) {
      const capKey = key[0].toUpperCase() + key.slice(1);
      if (!(capKey in result)) {
        result[capKey] = obj[key];
      }
    }
  });
  return result;
}

